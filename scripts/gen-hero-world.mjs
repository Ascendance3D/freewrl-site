import { writeFileSync } from "node:fs"

const f = (n) => Number(n.toFixed(4))
const deg = (d) => (d * Math.PI) / 180

// fingers: [angle from +X in degrees, start radius, length]
const FINGERS = [[168, 1.35, 2.2], [127, 1.45, 2.7], [93, 1.45, 3.1], [62, 1.45, 2.8], [33, 1.4, 2.3]]
const R = 0.3
function finger([a, r0, len], i) {
  const t = deg(a)
  const cx = Math.cos(t) * (r0 + len / 2), cy = Math.sin(t) * (r0 + len / 2)
  return `    Transform { # finger ${i + 1}
      translation ${f(cx)} ${f(cy)} 0
      rotation 0 0 1 ${f(t - Math.PI / 2)}
      children [
        Shape { appearance USE Glass geometry Cylinder { radius ${R} height ${len} top FALSE bottom FALSE } }
        Transform { translation 0 ${len / 2} 0 children Shape { appearance USE Glass geometry Sphere { radius ${R} } } }
        Transform { translation 0 ${-len / 2} 0 children Shape { appearance USE Glass geometry Sphere { radius ${R} } } }
      ]
    }`
}

// geodesic dome: icosahedron, frequency 3, upper hemisphere edges only
function geodesic(radius, freq) {
  const p = (1 + Math.sqrt(5)) / 2
  const V = [[-1, p, 0], [1, p, 0], [-1, -p, 0], [1, -p, 0], [0, -1, p], [0, 1, p], [0, -1, -p], [0, 1, -p], [p, 0, -1], [p, 0, 1], [-p, 0, -1], [-p, 0, 1]]
  const F = [[0, 11, 5], [0, 5, 1], [0, 1, 7], [0, 7, 10], [0, 10, 11], [1, 5, 9], [5, 11, 4], [11, 10, 2], [10, 7, 6], [7, 1, 8], [3, 9, 4], [3, 4, 2], [3, 2, 6], [3, 6, 8], [3, 8, 9], [4, 9, 5], [2, 4, 11], [6, 2, 10], [8, 6, 7], [9, 8, 1]]
  const pts = [], key = new Map(), edges = new Set()
  const norm = (v) => { const l = Math.hypot(...v); return v.map((c) => (c / l) * radius) }
  const idx = (v) => { const n = norm(v); const k = n.map((c) => c.toFixed(3)).join(","); if (!key.has(k)) { key.set(k, pts.length); pts.push(n) } return key.get(k) }
  const lerp = (a, b, t) => a.map((c, i) => c + (b[i] - c) * t)
  for (const [a, b, c] of F) {
    const A = V[a], B = V[b], C = V[c], grid = []
    for (let i = 0; i <= freq; i++) { grid.push([]); for (let j = 0; j <= freq - i; j++) grid[i].push(idx(lerp(lerp(A, B, i / freq), C, j / freq))) }
    const add = (u, v) => { if (u !== v) edges.add(u < v ? `${u},${v}` : `${v},${u}`) }
    for (let i = 0; i <= freq; i++) for (let j = 0; j <= freq - i; j++) {
      if (j < freq - i) add(grid[i][j], grid[i][j + 1])
      if (i < freq - i + 0 && i + 1 <= freq && j <= freq - i - 1) { add(grid[i][j], grid[i + 1][j]); add(grid[i][j + 1], grid[i + 1][j]) }
    }
  }
  const floor = -0.05 * radius
  const kept = [...edges].map((e) => e.split(",").map(Number)).filter(([u, v]) => pts[u][1] >= floor && pts[v][1] >= floor)
  return { pts, kept }
}
const dome = geodesic(8.5, 3)

// ground grid
const G = 12, step = 1
const gpts = [], gidx = []
for (let i = -G; i <= G; i += step) {
  gpts.push([i, 0, -G], [i, 0, G], [-G, 0, i], [G, 0, i])
  const b = gpts.length - 4; gidx.push(`${b} ${b + 1} -1`, `${b + 2} ${b + 3} -1`)
}

